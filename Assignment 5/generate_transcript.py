def dump(title, method, path, req_headers=None, body=None, query=None):
    url = f"{BASE}{path}"
    hdrs = dict(req_headers or {})
    # show curl -v style
    q = ""
    if query:
        from urllib.parse import urlencode
        q = "?" + urlencode(query)
        url = f"{BASE}{path}{q}"
    out.append("")
    out.append(f"# === {title} ===")
    # request
    out.append(f"> {method} {path}{q} HTTP/1.1")
    out.append(f"> Host: localhost:5001")
    for k,v in (req_headers or {}).items():
        out.append(f"> {k}: {v}")
    if body is not None:
        out.append(f"> Content-Type: application/json")
        out.append("")
        out.append(json.dumps(body, indent=2))
    else:
        out.append("")
    # actual call
    kwargs = {}
    if req_headers:
        kwargs["headers"] = req_headers
    if body is not None:
        kwargs["json"] = body
    if query:
        kwargs["params"] = query
    if method == "GET":
        r = requests.get(url, **kwargs)
    elif method == "POST":
        r = requests.post(f"{BASE}{path}", **kwargs)
    elif method == "PATCH":
        r = requests.patch(f"{BASE}{path}", **kwargs)
    elif method == "OPTIONS":
        r = requests.options(f"{BASE}{path}", **kwargs)
    elif method == "DELETE":
        r = requests.delete(f"{BASE}{path}", **kwargs)
    else:
        r = requests.request(method, f"{BASE}{path}", **kwargs)
    # response
    out.append(f"< HTTP/1.1 {r.status_code} {r.reason}")
    for k in ["Content-Type","Location","ETag","Cache-Control","Content-Encoding","Content-Length","X-RateLimit-Limit","X-RateLimit-Remaining","Retry-After","Allow","Access-Control-Allow-Origin","Access-Control-Allow-Methods","Access-Control-Allow-Headers","X-Content-Type-Options","Strict-Transport-Security","Idempotency-Key","Idempotency-Replayed","WWW-Authenticate","Date","Server"]:
        if k in r.headers:
            out.append(f"< {k}: {r.headers[k]}")
    out.append("<")
    try:
        j = r.json()
        out.append(json.dumps(j, indent=2))
    except:
        if r.content:
            out.append(r.text[:2000])
        else:
            out.append("(no body)")
    out.append("")
    return r

