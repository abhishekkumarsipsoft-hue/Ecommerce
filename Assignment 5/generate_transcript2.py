out = []

def dump(title, method, path, req_headers=None, body=None):
    url = f"{BASE}{path}"
    headers = dict(req_headers or {})
    out.append(f"# === {title} ===")
    out.append(f"> {method} {path} HTTP/1.1")
    out.append(f"> Host: localhost:5001")
    for k,v in headers.items():
        out.append(f"> {k}: {v}")
    if body is not None:
        out.append(f"> Content-Type: application/json")
        out.append("")
        out.append(json.dumps(body, indent=2))
    else:
        out.append("")
    kwargs = {"headers": headers}
    if body is not None:
        kwargs["json"] = body
    if method == "GET":
        r = requests.get(url, **kwargs)
    elif method == "POST":
        r = requests.post(url, **kwargs)
    elif method == "PATCH":
        r = requests.patch(url, **kwargs)
    elif method == "OPTIONS":
        r = requests.options(url, **kwargs)
    else:
        r = requests.request(method, url, **kwargs)
    out.append(f"< HTTP/1.1 {r.status_code} {r.reason}")
    for k in ["Content-Type","Location","ETag","Cache-Control","Content-Encoding","Content-Length","X-RateLimit-Limit","X-RateLimit-Remaining","Retry-After","Allow","Access-Control-Allow-Origin","Access-Control-Allow-Methods","Access-Control-Allow-Headers","X-Content-Type-Options","Strict-Transport-Security","Idempotency-Key","Idempotency-Replayed","WWW-Authenticate","Date","Server"]:
        if k in r.headers:
            out.append(f"< {k}: {r.headers[k]}")
    out.append("<")
    try:
        if r.content and "application/json" in r.headers.get("Content-Type",""):
            out.append(json.dumps(r.json(), indent=2))
        elif r.content:
            out.append(r.text[:2000])
        else:
            out.append("(no body)")
    except:
        out.append(r.text[:2000] if r.text else "(no body)")
    out.append("")
    return r

