import requests, json, os, textwrap
BASE = "http://localhost:5001"
out_lines = []
def log(cmd, resp):
    out_lines.append(f"$ {cmd}")
    out_lines.append(f"HTTP/1.1 {resp.status_code} {resp.reason}")
    for k,v in resp.headers.items():
        if k.lower() in ("content-type","location","idempotency-key","idempotency-replayed","content-length"):
            out_lines.append(f"{k}: {v}")
    out_lines.append("")
    try:
        out_lines.append(json.dumps(resp.json(), indent=2))
    except:
        out_lines.append(resp.text)
    out_lines.append("")
    out_lines.append("-" * 60)
    out_lines.append("")

payload = {"user_id":"user_abhi_01","address_id":"addr_01","items":[{"product_id":"prod_001","product_name":"Urban Daypack 25L","unit_price":899,"quantity":2}],"total_amount":1798}
idem = "11111111-2222-3333-4444-555555555555"

# 1 create
cmd1 = f'curl -i -X POST {BASE}/api/orders -H "Content-Type: application/json" -H "Idempotency-Key: {idem}" -d \'{{...}}\''
r1 = requests.post(f"{BASE}/api/orders", json=payload, headers={"Idempotency-Key": idem})
log(cmd1, r1)
oid1 = r1.json()["id"]

# 2 repeat same key
cmd2 = f'curl -i -X POST {BASE}/api/orders -H "Content-Type: application/json" -H "Idempotency-Key: {idem}" -d \'{{same body}}\'  # replay'
r2 = requests.post(f"{BASE}/api/orders", json=payload, headers={"Idempotency-Key": idem})
log(cmd2, r2)

# 3 malformed body (missing address_id etc.)
bad = {"user_id":"u1"}
cmd3 = f'curl -i -X POST {BASE}/api/orders -H "Content-Type: application/json" -d \'{json.dumps(bad)}\''
r3 = requests.post(f"{BASE}/api/orders", json=bad)
log(cmd3, r3)

# 4 missing resource
cmd4 = f'curl -i {BASE}/api/orders/00000000-0000-0000-0000-000000000000'
r4 = requests.get(f"{BASE}/api/orders/00000000-0000-0000-0000-000000000000")
log(cmd4, r4)

# 5 filtered list (query string)
cmd5 = f'curl -i "{BASE}/api/orders?user_id=user_abhi_01&status=PENDING_PAYMENT"'
r5 = requests.get(f"{BASE}/api/orders", params={"user_id":"user_abhi_01","status":"PENDING_PAYMENT"})
log(cmd5, r5)

# 6 cancellation sub-resource (202)
# need fresh order
idem2 = "22222222-3333-4444-5555-666666666666"
r_new = requests.post(f"{BASE}/api/orders", json=payload, headers={"Idempotency-Key": idem2})
oid2 = r_new.json()["id"]
cmd6 = f'curl -i -X POST {BASE}/api/orders/{oid2}/cancellation -H "Content-Type: application/json" -d \'{{"reason":"Ordered wrong size"}}\''
r6 = requests.post(f"{BASE}/api/orders/{oid2}/cancellation", json={"reason":"Ordered wrong size"})
log(cmd6, r6)

# 7 state conflict: cancel again -> 409
cmd7 = f'curl -i -X POST {BASE}/api/orders/{oid2}/cancellation -H "Content-Type: application/json" -d \'{{"reason":"Again"}}\'  # 409 conflict'
r7 = requests.post(f"{BASE}/api/orders/{oid2}/cancellation", json={"reason":"Again"})
log(cmd7, r7)

# 8 another conflict: PATCH to transition to same status -> 409, and shipped->cancel -> 422
idem3 = "33333333-4444-5555-6666-777777777777"
r_new3 = requests.post(f"{BASE}/api/orders", json=payload, headers={"Idempotency-Key": idem3})
oid3 = r_new3.json()["id"]
# advance to PAID then PACKED then SHIPPED
for s in ["PAID","PACKED","SHIPPED"]:
    requests.patch(f"{BASE}/api/orders/{oid3}/status", json={"status": s})
cmd8a = f'curl -i -X POST {BASE}/api/orders/{oid3}/cancellation -d \'{{"reason":"Too late"}}\'  # 422 unprocessable (shipped)'
r8a = requests.post(f"{BASE}/api/orders/{oid3}/cancellation", json={"reason":"Too late"})
log(cmd8a, r8a)

cmd8b = f'curl -i -X PATCH {BASE}/api/orders/{oid3}/status -d \'{{"status":"PACKED"}}\'  # 409 conflict (illegal transition)'
r8b = requests.patch(f"{BASE}/api/orders/{oid3}/status", json={"status":"PACKED"})
log(cmd8b, r8b)

# 9 read single order 200
cmd9 = f'curl -i {BASE}/api/orders/{oid1}'
r9 = requests.get(f"{BASE}/api/orders/{oid1}")
log(cmd9, r9)

